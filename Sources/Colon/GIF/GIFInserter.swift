import AppKit
import Carbon.HIToolbox
import ColonCore

/// Pastes a GIF into the frontmost app: one pasteboard item with the file URL and the GIF data
/// (no plain text), a synthetic ⌘V, then the user's previous pasteboard comes back after 1.5 s.
/// GIFs always paste, whatever the emoji `insertionMethod` is.
@MainActor
enum GIFInserter {
    static let gifType = NSPasteboard.PasteboardType("com.compuserve.gif")
    static let restoreDelay: TimeInterval = 1.5
    /// Copies stay at least this long (apps may read the file lazily), then go at the next launch.
    nonisolated static let retention: TimeInterval = 24 * 60 * 60

    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    /// `~/Library/Caches/so.slayer.Colon/GIFs`
    nonisolated static let directory: URL = {
        let caches = FileManager.default.urls(for: .cachesDirectory, in: .userDomainMask).first
            ?? FileManager.default.temporaryDirectory
        return caches.appendingPathComponent("so.slayer.Colon", isDirectory: true)
            .appendingPathComponent("GIFs", isDirectory: true)
    }()

    /// Writes the GIF to `GIFs/giphy-<id>.gif` (named after the GIF, never the query).
    static func writeFile(_ data: Data, for result: GIFResult) throws -> URL {
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        let url = directory.appendingPathComponent(result.fileName)
        try data.write(to: url, options: .atomic)
        return url
    }

    /// The single pasteboard item: file URL + GIF data + nspasteboard.org markers.
    static func makeItem(data: Data, fileURL: URL) -> NSPasteboardItem {
        let item = NSPasteboardItem()
        item.setString(fileURL.absoluteString, forType: .fileURL)
        item.setData(data, forType: gifType)
        item.setData(Data(), forType: transientType)
        item.setData(Data(), forType: autoGeneratedType)
        return item
    }

    /// With `paste`, sends the item to the frontmost app with ⌘V; otherwise leaves it on the
    /// pasteboard (e.g. when the target is Colon itself or no longer frontmost).
    static func insert(_ data: Data, fileURL: URL, paste: Bool) {
        let item = makeItem(data: data, fileURL: fileURL)
        if paste {
            Self.paste(item: item, restoreAfter: restoreDelay)
        } else {
            NSPasteboard.general.clearContents()
            NSPasteboard.general.writeObjects([item])
        }
    }

    /// Removes copies older than `retention`. Called at launch, off the main thread.
    nonisolated static func pruneOldFiles(now: Date = Date()) {
        let manager = FileManager.default
        guard let files = try? manager.contentsOfDirectory(at: directory, includingPropertiesForKeys: [.contentModificationDateKey],
                                                           options: [.skipsHiddenFiles]) else { return }
        let cutoff = now.addingTimeInterval(-retention)
        for file in files {
            let modified = (try? file.resourceValues(forKeys: [.contentModificationDateKey]))?.contentModificationDate
            if (modified ?? .distantPast) < cutoff { try? manager.removeItem(at: file) }
        }
    }

    // MARK: Paste (mirrors the input-owned `Inserter.paste(item:restoreAfter:)` contract)

    private static var savedPasteboard: [NSPasteboardItem]?
    private static var pasteboardChangeCount = 0
    private static var restoreWork: DispatchWorkItem?

    /// Saves the user's pasteboard once (even across rapid inserts), writes `item`, sends ⌘V and
    /// restores the saved contents after `restoreAfter` unless something else wrote meanwhile.
    /// Same signature as `Inserter.paste(item:restoreAfter:)`; switch to it at integration.
    private static func paste(item: NSPasteboardItem, restoreAfter: TimeInterval) {
        let pasteboard = NSPasteboard.general
        restoreWork?.cancel()
        if savedPasteboard == nil {
            savedPasteboard = (pasteboard.pasteboardItems ?? []).map { item in
                let copy = NSPasteboardItem()
                for type in item.types {
                    if let data = item.data(forType: type) { copy.setData(data, forType: type) }
                }
                return copy
            }
        }
        pasteboard.clearContents()
        pasteboard.writeObjects([item])
        pasteboardChangeCount = pasteboard.changeCount

        let keyCode = KeyLayout.keyCode(for: "v") ?? CGKeyCode(kVK_ANSI_V)
        SyntheticEvent.keyPress(keyCode, flags: .maskCommand).forEach { $0.post(tap: .cghidEventTap) }

        let work = DispatchWorkItem {
            MainActor.assumeIsolated { restorePasteboard() }
        }
        restoreWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + restoreAfter, execute: work)
    }

    private static func restorePasteboard() {
        defer {
            savedPasteboard = nil
            restoreWork = nil
        }
        let pasteboard = NSPasteboard.general
        // If something else wrote to the pasteboard meanwhile (the user copied), keep that.
        guard pasteboard.changeCount == pasteboardChangeCount, let saved = savedPasteboard else { return }
        pasteboard.clearContents()
        if !saved.isEmpty { pasteboard.writeObjects(saved) }
    }
}
